/**
 * ズーム段階ごとの地形シルエット。
 *
 * **画像素材は使わない**方針なので、文字列のドット絵で持つ。
 * 1文字が1マスではなく、キャンバスに合わせて拡大される背景なので、
 * 解像度は「輪郭がそれと分かる」程度で足りる。
 *
 * | 文字 | 意味 |
 * |---|---|
 * | `#` | 陸 |
 * | `~` | 水（湾・湖） |
 * | `*` | 緑地（皇居） |
 * | `.` | 何も描かない（`sea` が true なら海のまま） |
 *
 * **街は必ずキャンバスの中央から広がる。** 中央が陸になっていない地形を足すと、
 * 海の上に街が生えることになるので注意（丸の内＝東京＝日本の中央付近＝
 * 世界地図の中央、と重なるように描いてある）。
 */

export type Terrain = {
  /** 背景を海で塗るか。列島・世界地図は海の上に描く */
  sea: boolean;
  /** 収め方。`cover` は画面いっぱいに広げ、`contain` は全体を収める */
  fit: "cover" | "contain";
  rows: string[];
};

