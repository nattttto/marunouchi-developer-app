/** ビットマップをキャンバスへ収めるときの拡大率と余白 */
export type TerrainLayout = {
  scale: number;
  offsetX: number;
  offsetY: number;
  cols: number;
  rows: number;
};

/**
 * 地形の収め方を1か所で決める。
 * 描画（`mapRender`）と、区画を置ける場所の判定（`mapScene`）が
 * 別々に計算すると、見えている陸と建てられる陸がずれる。
 */
export function getTerrainLayout(
  terrain: Terrain,
  width: number,
  height: number
): TerrainLayout {
  const cols = terrain.rows[0].length;
  const rows = terrain.rows.length;
  const scale =
    terrain.fit === "cover"
      ? Math.max(width / cols, height / rows)
      : Math.min(width / cols, height / rows);

  return {
    scale,
    offsetX: (width - cols * scale) / 2,
    offsetY: (height - rows * scale) / 2,
    cols,
    rows,
  };
}

/** キャンバス上の座標がどの地形文字にあたるか。範囲外は `.` */
export function terrainAt(
  terrain: Terrain,
  layout: TerrainLayout,
  x: number,
  y: number
): string {
  const c = Math.floor((x - layout.offsetX) / layout.scale);
  const r = Math.floor((y - layout.offsetY) / layout.scale);
  if (c < 0 || r < 0 || c >= layout.cols || r >= layout.rows) return ".";
  return terrain.rows[r][c];
}
